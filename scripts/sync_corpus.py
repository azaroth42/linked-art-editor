#!/usr/bin/env python3
"""Copy the linked.art example records into the golden corpus, byte-for-byte.

Usage (from the repository root, standard library only):

    python3 scripts/sync_corpus.py [--source /path/to/linked.art]

What it does (Phase 0, Step 0.4):

1. Copies every ``docs/example/<category>/**/*.json`` record from the linked.art checkout into
   ``tests/corpus/linkedart/<category>-<sub-path>.json``. The examples are nested one level below
   the category (``object/nightwatch/1.json``), so the sub-path keeps that level:
   ``object/nightwatch/1.json`` -> ``object-nightwatch-1.json``; ``object/1.json`` ->
   ``object-1.json``.
2. Skips JSON files that are not Linked Art records (not an object with ``@context``, ``id`` and
   ``type``) and lists them.
3. Copies the pinned context ``docs/ns/v1/linked-art.json`` to ``profiles/context/v1.json``.
4. Rewrites the generated linked.art section of ``tests/corpus/SOURCE.md`` with the source commit.

It never deletes corpus files. Files under ``tests/corpus/linkedart/`` that no longer exist in
the source are reported so a human can decide what to do with them.
"""

from __future__ import annotations

import argparse
import json
import re
import shutil
import subprocess
import sys
from pathlib import Path

REPO_ROOT = Path(__file__).resolve().parents[1]
DEFAULT_SOURCE = Path("/Users/rs2668/Development/linked-art/linked.art")
CORPUS_DIR = REPO_ROOT / "tests" / "corpus"
TARGET_DIR = CORPUS_DIR / "linkedart"
SOURCE_MD = CORPUS_DIR / "SOURCE.md"
CONTEXT_TARGET = REPO_ROOT / "profiles" / "context" / "v1.json"
EXAMPLE_SUBDIR = Path("docs/example")
CONTEXT_SOURCE = Path("docs/ns/v1/linked-art.json")
BEGIN_MARKER = "<!-- sync_corpus:linkedart:begin -->"
END_MARKER = "<!-- sync_corpus:linkedart:end -->"


def target_name(relative: Path) -> str:
    """Map ``<category>/<sub>/<n>.json`` to ``<category>-<sub>-<n>.json``."""
    return "-".join(relative.with_suffix("").parts) + ".json"


def is_record(raw: bytes) -> bool:
    """True when the bytes are a JSON object with ``@context``, ``id`` and ``type``."""
    try:
        data = json.loads(raw)
    except ValueError:
        return False
    return isinstance(data, dict) and all(key in data for key in ("@context", "id", "type"))


def git(source: Path, *args: str) -> str:
    """Run a read-only git command in the source checkout and return its stdout."""
    result = subprocess.run(
        ["git", "-C", str(source), *args], check=True, capture_output=True, text=True
    )
    return result.stdout.strip()


def code_list(items: list[str]) -> str:
    """Render items as a comma-separated list of inline code, or ``none``."""
    return ", ".join(f"`{item}`" for item in items) if items else "none"


def render_source_block(
    commit: str, commit_date: str, dirty: list[str], copied: int, skipped: list[str]
) -> str:
    """Render the generated linked.art section of SOURCE.md."""
    lines = [
        BEGIN_MARKER,
        "## linked.art examples (`linkedart/`)",
        "",
        "Generated by `scripts/sync_corpus.py`; do not edit by hand.",
        "",
        "| | |",
        "| :-- | :-- |",
        "| Repository | `linked-art/linked.art` (https://github.com/linked-art/linked.art) |",
        f"| Commit | `{commit}` ({commit_date}) |",
        f"| Source paths | `{EXAMPLE_SUBDIR}/<category>/**/*.json` and `{CONTEXT_SOURCE}` |",
        f"| Files copied | {copied} records into `linkedart/`, plus the context into "
        "`profiles/context/v1.json` |",
        "| Naming | `<category>/<sub>/<n>.json` -> `<category>-<sub>-<n>.json` |",
        f"| Skipped (not records) | {code_list(skipped)} |",
        f"| Uncommitted changes in source paths at sync time | {code_list(dirty)} |",
        END_MARKER,
    ]
    return "\n".join(lines)


def update_source_md(block: str) -> None:
    """Replace the generated block in SOURCE.md, or append it if the file has none."""
    text = SOURCE_MD.read_text(encoding="utf-8") if SOURCE_MD.exists() else "# Corpus sources\n"
    pattern = re.compile(re.escape(BEGIN_MARKER) + ".*?" + re.escape(END_MARKER), re.DOTALL)
    if pattern.search(text):
        text = pattern.sub(lambda _: block, text)
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    SOURCE_MD.write_text(text, encoding="utf-8")


def sync(source: Path) -> int:
    """Copy examples and the context from ``source``; return a process exit code."""
    examples = source / EXAMPLE_SUBDIR
    if not examples.is_dir():
        print(f"error: {examples} does not exist", file=sys.stderr)
        return 1

    TARGET_DIR.mkdir(parents=True, exist_ok=True)
    written: dict[str, Path] = {}
    skipped: list[str] = []
    for path in sorted(examples.rglob("*.json")):
        relative = path.relative_to(examples)
        raw = path.read_bytes()
        if not is_record(raw):
            skipped.append(str(relative))
            continue
        name = target_name(relative)
        if name in written:
            print(f"error: {relative} and {written[name]} both map to {name}", file=sys.stderr)
            return 1
        written[name] = relative
        shutil.copyfile(path, TARGET_DIR / name)

    CONTEXT_TARGET.parent.mkdir(parents=True, exist_ok=True)
    shutil.copyfile(source / CONTEXT_SOURCE, CONTEXT_TARGET)

    commit = git(source, "rev-parse", "HEAD")
    commit_date = git(source, "show", "-s", "--format=%cs", "HEAD")
    status = git(source, "status", "--porcelain", "--", str(EXAMPLE_SUBDIR), str(CONTEXT_SOURCE))
    dirty = [line[3:] for line in status.splitlines() if line]
    update_source_md(render_source_block(commit, commit_date, dirty, len(written), skipped))

    stale = sorted(p.name for p in TARGET_DIR.glob("*.json") if p.name not in written)
    print(f"copied {len(written)} records from {source} @ {commit[:12]}")
    print(f"copied context to {CONTEXT_TARGET.relative_to(REPO_ROOT)}")
    for name in skipped:
        print(f"skipped (not a Linked Art record): {name}")
    for name in dirty:
        print(f"warning: uncommitted change in source: {name}")
    for name in stale:
        print(f"warning: {name} is in the corpus but no longer in the source (not deleted)")
    return 0


def main(argv: list[str] | None = None) -> int:
    """Parse arguments and run the sync."""
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument(
        "--source",
        type=Path,
        default=DEFAULT_SOURCE,
        help=f"linked.art checkout (default: {DEFAULT_SOURCE})",
    )
    args = parser.parse_args(argv)
    return sync(args.source.resolve())


if __name__ == "__main__":
    sys.exit(main())
